/**
 * Runtime proof that a mutation's options reached the Director.
 *
 * The mutation script itself runs before `scriptedmode.nut` merges `MutationOptions` into
 * `DirectorOptions`, so a top-level `printl` there prints the table before the merge. A
 * `logic_script` attached to the map registers game-event hooks; by `round_start` /
 * `player_spawn` the merged table is `SessionOptions`, and printing it there is the proof.
 *
 * The event-hook shape is the one that worked on a real map. `AddThinkToEnt` and a delayed
 * `EntFire(RunScriptCode)` from `script_execute` did not produce a line in the same runs.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { defineTool } from "../../../core/typescript/mcp/registry.js";
import { resolveInput, resolveVmfInput } from "../../../core/typescript/tools/paths.js";
import { addEntities, verifyEntities } from "../../../maps/typescript/tools/entityfamilies.js";

const DEFAULT_KEYS = [
  "BoomerLimit",
  "SmokerLimit",
  "HunterLimit",
  "SpitterLimit",
  "JockeyLimit",
  "ChargerLimit",
  "TankLimit",
  "WitchLimit",
  "MaxSpecials",
  "MinSpecials",
  "MaxConcurrentSpecials",
];

export function optionsProbeScript(keys: readonly string[]): string {
  const keyList = keys.map((key) => `"${key.replace(/"/g, "")}"`).join(", ");
  return `// Generated by L4D2-HSMCP write_options_probe.
HSMCP_OPTIONS_KEYS <- [${keyList}];
HSMCP_OPTIONS_PRINTED <- false;

function HSMCP_OptionsReport()
{
\tif ( HSMCP_OPTIONS_PRINTED ) return;
\tHSMCP_OPTIONS_PRINTED = true;
\tif ( SessionOptions == null )
\t{
\t\tprintl( "[HSMCP_OPTIONS] no SessionOptions" );
\t}
\telse
\t{
\t\tif ( SessionState != null )
\t\t{
\t\t\tprintl( "[HSMCP_OPTIONS] ModeName=" + SessionState.ModeName );
\t\t}
\t\tforeach ( key in HSMCP_OPTIONS_KEYS )
\t\t{
\t\t\tprintl( "[HSMCP_OPTIONS] " + key + "=" + SessionOptions[key] );
\t\t}
\t}
\tprintl( "HSMCP_OPTIONS_DONE" );
}

function OnGameEvent_round_start( params ) { HSMCP_OptionsReport(); }
function OnGameEvent_player_spawn( params ) { HSMCP_OptionsReport(); }
function OnGameEvent_player_first_spawn( params ) { HSMCP_OptionsReport(); }
`;
}

export const writeOptionsProbeTool = defineTool({
  name: "write_options_probe",
  description:
    "Writes a `logic_script` and a `.nut` that print the Director's effective merged " +
    "`SessionOptions` on `round_start` / `player_spawn`, then `HSMCP_OPTIONS_DONE`. This is " +
    "the runtime proof that `MutationOptions` reached the Director: the mutation script " +
    "itself runs before `scriptedmode.nut` merges the tables. The event hooks are the shape " +
    "that worked on a real map; a think/EntFire delay in `script_execute` did not. For a " +
    "compiled map, copy the `.bsp` and add the returned entity with `edit_bsp_entities`; " +
    "`run_map_test` installs the script with `scriptsDir` and launches with `mode`. Guarded.",
  realm: "map",
  guarded: true,
  meta: { "anthropic/requiresUserInteraction": true },
  inputSchema: {
    path: z.string().describe("Path to the .vmf to add the logic_script to."),
    keys: z
      .array(z.string().min(1))
      .min(1)
      .default(DEFAULT_KEYS)
      .describe("SessionOptions keys to print, e.g. BoomerLimit, MaxSpecials."),
    scriptName: z
      .string()
      .min(1)
      .default("hsmcp_options_probe")
      .describe("Base name of the `.nut` and the `vscripts` value."),
    scriptsDir: z
      .string()
      .optional()
      .describe("Directory for the `.nut`; defaults to <vmf dir>/scripts/vscripts."),
    targetname: z.string().optional().describe("Targetname for the logic_script entity."),
    confirm: z.boolean().default(false),
  },
  outputSchema: {
    path: z.string(),
    scriptPath: z.string(),
    scriptsDir: z.string(),
    logicScriptId: z.number().nullable(),
    entity: z.object({ classname: z.string(), vscripts: z.string() }),
    keys: z.array(z.string()),
    markers: z.array(
      z.object({ name: z.string(), pattern: z.string(), withinSeconds: z.number() }),
    ),
    nextStep: z.string(),
  },
  handler: async (args, ctx) => {
    const vmf = resolveVmfInput(args.path, ctx.config);
    const keys = args.keys ?? DEFAULT_KEYS;
    for (const key of keys) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) {
        throw new Error(`"${key}" is not an identifier SessionOptions can be indexed by`);
      }
    }
    const scriptName = args.scriptName ?? "hsmcp_options_probe";
    if (!/^[A-Za-z0-9_]+$/.test(scriptName)) {
      throw new Error("scriptName must be letters, digits and underscores");
    }
    const scriptsDir = args.scriptsDir
      ? resolveInput(args.scriptsDir, ctx.config)
      : join(dirname(vmf), "scripts", "vscripts");
    mkdirSync(scriptsDir, { recursive: true });
    const scriptPath = join(scriptsDir, `${scriptName}.nut`);
    writeFileSync(scriptPath, optionsProbeScript(keys), "utf8");

    const keyvalues: Record<string, string> = {
      classname: "logic_script",
      vscripts: scriptName,
      origin: "0 0 0",
      ...(args.targetname !== undefined ? { targetname: args.targetname } : {}),
    };
    const [logicScriptId = null] = await addEntities(vmf, [keyvalues], ctx);
    verifyEntities(vmf, [logicScriptId], ["logic_script"]);

    return {
      path: vmf,
      scriptPath,
      scriptsDir,
      logicScriptId,
      entity: { classname: "logic_script", vscripts: scriptName },
      keys,
      markers: [
        {
          name: "first_option",
          pattern: `\\[HSMCP_OPTIONS\\] ${keys[0]}=`,
          withinSeconds: 120,
        },
        {
          name: "options_done",
          pattern: "HSMCP_OPTIONS_DONE",
          withinSeconds: 120,
        },
      ],
      nextStep:
        "Compile the VMF, then call run_map_test with `scriptsDir` set to this directory, " +
        "`mode` set to the mutation, and `markerOrder: \"any\"`. For a compiled stock map, " +
        "copy the .bsp and add the `entity` above with edit_bsp_entities instead.",
    };
  },
});

export const optionsProbeTools = [writeOptionsProbeTool];
