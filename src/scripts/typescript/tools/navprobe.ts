/**
 * Runtime verification of nav attributes.
 *
 * `func_nav_attribute_region` applies its bits when the entity spawns, which is after the nav
 * file was generated and saved. A nav dump written during generation can therefore say 0 for
 * an area that has the bit in the running map. VScript's `TerrorNavArea` exposes
 * `GetSpawnAttributes`, `GetAttributes` and `HasSpawnAttributes`, so this tool samples the
 * live mesh at chosen points and prints `HSMCP_NAV <name> HAS|MISSING`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { defineTool } from "../../../core/typescript/mcp/registry.js";
import { resolveInput, resolveVmfInput } from "../../../core/typescript/tools/paths.js";
import { addEntities, verifyEntities } from "../../../maps/typescript/tools/entityfamilies.js";
import {
  NAV_SPAWN_BITS,
  type AttributeName,
} from "../../../maps/typescript/tools/navattrs.js";

const POINT = z.object({
  name: z.string().min(1),
  origin: z.tuple([z.number(), z.number(), z.number()]),
  attributes: z
    .array(z.enum(Object.keys(NAV_SPAWN_BITS) as [AttributeName, ...AttributeName[]]))
    .default([])
    .describe("Spawn attributes the area must have; each is tested with HasSpawnAttributes."),
});

function scriptText(
  points: ReadonlyArray<{ name: string; origin: readonly number[]; bits: number }>,
  atSeconds: number,
): string {
  const rows = points
    .map(
      (point) =>
        `\t[ "${point.name.replace(/"/g, "")}", Vector( ${point.origin.join(", ")} ), ${point.bits} ]`,
    )
    .join(",\n");
  return `// Generated by L4D2-HSMCP write_nav_probe.
HSMCP_NAV_POINTS <- [
${rows}
];
HSMCP_NAV_DELAY <- ${atSeconds};
HSMCP_NAV_START <- 0;

function HSMCP_NavProbeThink()
{
\tif ( Time() - HSMCP_NAV_START < HSMCP_NAV_DELAY ) return 0.25;
\tforeach ( point in HSMCP_NAV_POINTS )
\t{
\t\tlocal area = NavMesh.GetNearestNavArea( point[1], 2048, true, true );
\t\tif ( area == null )
\t\t{
\t\t\tprintl( "HSMCP_NAV " + point[0] + " NONE" );
\t\t\tcontinue;
\t\t}
\t\tprintl( "HSMCP_NAV " + point[0] + " spawn=" + area.GetSpawnAttributes() + " base=" + area.GetAttributes() );
\t\tif ( point[2] != 0 )
\t\t{
\t\t\tif ( area.HasSpawnAttributes( point[2] ) )
\t\t\t\tprintl( "HSMCP_NAV " + point[0] + " HAS" );
\t\t\telse
\t\t\t\tprintl( "HSMCP_NAV " + point[0] + " MISSING" );
\t\t}
\t}
\tprintl( "HSMCP_NAV_DONE" );
\treturn -1;
}

HSMCP_NAV_START = Time();
AddThinkToEnt( self, "HSMCP_NavProbeThink" );
`;
}

export const writeNavProbeTool = defineTool({
  name: "write_nav_probe",
  description:
    "Samples the live nav mesh with VScript at chosen points and prints spawn/base attributes " +
    "and whether each required attribute is present. This is the check for " +
    "`write_nav_attribute_region`: attributes are applied when the region entity spawns, " +
    "after the nav file was written. Writes a `logic_script` and `.nut`; pass `scriptsDir` to " +
    "`run_map_test`. Guarded.",
  realm: "map",
  guarded: true,
  meta: { "anthropic/requiresUserInteraction": true },
  inputSchema: {
    path: z.string().describe("Path to the .vmf, absolute or relative to the repo root."),
    points: z.array(POINT).min(1),
    atSeconds: z
      .number()
      .int()
      .min(1)
      .max(600)
      .default(8)
      .describe("Seconds after map spawn to sample; the region applies on spawn."),
    scriptName: z.string().min(1).default("hsmcp_nav_probe"),
    scriptsDir: z
      .string()
      .optional()
      .describe("Directory for the .nut; defaults to <vmf dir>/scripts/vscripts."),
    targetname: z.string().optional(),
    confirm: z.boolean().default(false),
  },
  outputSchema: {
    path: z.string(),
    scriptPath: z.string(),
    scriptsDir: z.string(),
    logicScriptId: z.number().nullable(),
    markers: z.array(
      z.object({ name: z.string(), pattern: z.string(), withinSeconds: z.number() }),
    ),
    nextStep: z.string(),
  },
  handler: async (args, ctx) => {
    const vmf = resolveVmfInput(args.path, ctx.config);
    const scriptName = args.scriptName ?? "hsmcp_nav_probe";
    if (!/^[A-Za-z0-9_]+$/.test(scriptName)) {
      throw new Error("scriptName must be letters, digits and underscores");
    }
    const atSeconds = args.atSeconds ?? 8;
    const points = (args.points ?? []).map((point) => ({
      name: point.name,
      origin: point.origin,
      bits: (point.attributes ?? []).reduce((bits, name) => bits | NAV_SPAWN_BITS[name], 0),
    }));
    const scriptsDir = args.scriptsDir
      ? resolveInput(args.scriptsDir, ctx.config)
      : join(dirname(vmf), "scripts", "vscripts");
    mkdirSync(scriptsDir, { recursive: true });
    const scriptPath = join(scriptsDir, `${scriptName}.nut`);
    writeFileSync(scriptPath, scriptText(points, atSeconds), "utf8");

    const keyvalues: Record<string, string> = {
      classname: "logic_script",
      vscripts: scriptName,
      origin: "0 0 0",
      ...(args.targetname !== undefined ? { targetname: args.targetname } : {}),
    };
    const [logicScriptId = null] = await addEntities(vmf, [keyvalues], ctx);
    verifyEntities(vmf, [logicScriptId], ["logic_script"]);

    return {
      path: vmf,
      scriptPath,
      scriptsDir,
      logicScriptId,
      markers: [
        ...points
          .filter((point) => point.bits !== 0)
          .map((point) => ({
            name: `${point.name}_attribute`,
            pattern: `HSMCP_NAV ${point.name} HAS`,
            withinSeconds: atSeconds + 60,
          })),
        {
          name: "nav_probe_done",
          pattern: "HSMCP_NAV_DONE",
          withinSeconds: atSeconds + 60,
        },
      ],
      nextStep:
        "Compile the VMF, then call run_map_test with `scriptsDir` and `markerOrder: \"any\"`. " +
        "The raw line `HSMCP_NAV <name> spawn=0x... base=0x...` is in the console log.",
    };
  },
});

export const navProbeTools = [writeNavProbeTool];
