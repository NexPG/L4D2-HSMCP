/**
 * A runtime class counter, written as VScript.
 *
 * `write_entity_probe` answers "does this targetname exist". It cannot answer "did the
 * Director spawn a `weapon_rifle`", because the spawned weapon has no name in the VMF and no
 * output to attach. VScript can iterate the live entity list by class, so this tool writes a
 * `logic_script` and a `.nut` that prints `HSMCP_CLASS <step> <class> <count>` at chosen
 * seconds. `run_map_test` installs the script through `scriptsDir` and matches the lines.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { defineTool } from "../../../core/typescript/mcp/registry.js";
import { resolveInput, resolveVmfInput } from "../../../core/typescript/tools/paths.js";
import { addEntities, verifyEntities } from "../../../maps/typescript/tools/entityfamilies.js";

function scriptText(
  classes: readonly string[],
  steps: readonly number[],
  positions: boolean,
  maxPositions: number,
): string {
  const classList = classes.map((name) => `"${name.replace(/"/g, "")}"`).join(", ");
  return `// Generated by L4D2-HSMCP write_class_probe.
HSMCP_CLASSES <- [${classList}];
HSMCP_STEPS <- [${steps.join(", ")}];
HSMCP_START <- 0;
HSMCP_NEXT <- 0;
HSMCP_DONE_PRINTED <- false;

function HSMCP_ClassProbe( step )
{
\tif ( step < 0 || step >= HSMCP_STEPS.len() ) return;
\tforeach ( classname in HSMCP_CLASSES )
\t{
\t\tlocal count = 0;
\t\tlocal entity = null;
\t\twhile ( ( entity = Entities.FindByClassname( entity, classname ) ) != null )
\t\t{
\t\t\tcount += 1;
\t\t}
\t\tprintl( "HSMCP_CLASS " + step + " " + classname + " " + count );
\t\tif ( ${positions ? "true" : "false"} && step == HSMCP_STEPS.len() - 1 )
\t\t{
\t\t\tlocal shown = 0;
\t\t\tlocal item = null;
\t\t\twhile ( ( item = Entities.FindByClassname( item, classname ) ) != null && shown < ${maxPositions} )
\t\t\t{
\t\t\t\tlocal origin = item.GetOrigin();
\t\t\t\tprintl( "HSMCP_CLASS_POS " + classname + " " + origin.x + " " + origin.y + " " + origin.z );
\t\t\t\tshown += 1;
\t\t\t}
\t\t}
\t}
}

function HSMCP_ClassProbeThink()
{
\tlocal now = Time();
\twhile ( HSMCP_NEXT < HSMCP_STEPS.len() && now - HSMCP_START >= HSMCP_STEPS[HSMCP_NEXT] )
\t{
\t\tHSMCP_ClassProbe( HSMCP_NEXT );
\t\tHSMCP_NEXT += 1;
\t}
\tif ( HSMCP_NEXT >= HSMCP_STEPS.len() )
\t{
\t\tif ( !HSMCP_DONE_PRINTED )
\t\t{
\t\t\tprintl( "HSMCP_CLASS_DONE" );
\t\t\tHSMCP_DONE_PRINTED = true;
\t\t}
\t\treturn -1;
\t}
\treturn 0.25;
}

HSMCP_START = Time();
AddThinkToEnt( self, "HSMCP_ClassProbeThink" );
`;
}

export const writeClassProbeTool = defineTool({
  name: "write_class_probe",
  description:
    "Writes a `logic_script` and a `.nut` that counts live entities by classname at chosen " +
    "seconds and prints `HSMCP_CLASS <step> <class> <count>`. Use it for items the Director " +
    "spawns (a `weapon_rifle_spawn` has no output on the weapon it creates), infected, or any " +
    "class with no targetname. `run_map_test` installs the script with `scriptsDir`; the " +
    "returned markers assert a nonzero count at the final step. Guarded.",
  realm: "map",
  guarded: true,
  meta: { "anthropic/requiresUserInteraction": true },
  inputSchema: {
    path: z.string().describe("Path to the .vmf, absolute or relative to the repo root."),
    classes: z
      .array(z.string().min(1))
      .min(1)
      .describe("Classnames to count, e.g. weapon_rifle, weapon_first_aid_kit, infected."),
    atSeconds: z
      .array(z.number().int().min(1).max(600))
      .min(1)
      .default([8, 16, 24])
      .describe("Seconds from map spawn to sample; must be ascending."),
    scriptName: z
      .string()
      .min(1)
      .default("hsmcp_class_probe")
      .describe("Base name of the .nut and the `vscripts` value."),
    positions: z
      .boolean()
      .default(false)
      .describe(
        "At the final sample, also print up to `maxPositions` origins per class as " +
          "`HSMCP_CLASS_POS <class> <x> <y> <z>`. Use it to see which side of a border the " +
          "Director spawned on.",
      ),
    maxPositions: z.number().int().min(1).max(500).default(50),
    scriptsDir: z
      .string()
      .optional()
      .describe("Directory for the .nut; defaults to <vmf dir>/scripts/vscripts."),
    targetname: z.string().optional().describe("Targetname for the logic_script entity."),
    confirm: z.boolean().default(false),
  },
  outputSchema: {
    path: z.string(),
    scriptPath: z.string(),
    scriptsDir: z.string(),
    logicScriptId: z.number().nullable(),
    classes: z.array(z.string()),
    atSeconds: z.array(z.number()),
    markers: z.array(
      z.object({ name: z.string(), pattern: z.string(), withinSeconds: z.number() }),
    ),
    nextStep: z.string(),
  },
  handler: async (args, ctx) => {
    const vmf = resolveVmfInput(args.path, ctx.config);
    const classes = args.classes ?? [];
    if (classes.length === 0) throw new Error("give at least one classname");
    const steps = [...(args.atSeconds ?? [8, 16, 24])];
    for (let index = 1; index < steps.length; index += 1) {
      if (steps[index]! <= steps[index - 1]!) {
        throw new Error("atSeconds must be strictly ascending");
      }
    }
    const scriptName = args.scriptName ?? "hsmcp_class_probe";
    if (!/^[A-Za-z0-9_]+$/.test(scriptName)) {
      throw new Error("scriptName must be letters, digits and underscores");
    }
    const scriptsDir = args.scriptsDir
      ? resolveInput(args.scriptsDir, ctx.config)
      : join(dirname(vmf), "scripts", "vscripts");
    mkdirSync(scriptsDir, { recursive: true });
    const scriptPath = join(scriptsDir, `${scriptName}.nut`);
    writeFileSync(
      scriptPath,
      scriptText(classes, steps, args.positions ?? false, args.maxPositions ?? 50),
      "utf8",
    );

    const keyvalues: Record<string, string> = {
      classname: "logic_script",
      vscripts: scriptName,
      origin: "0 0 0",
      ...(args.targetname !== undefined ? { targetname: args.targetname } : {}),
    };
    const [logicScriptId = null] = await addEntities(vmf, [keyvalues], ctx);
    verifyEntities(vmf, [logicScriptId], ["logic_script"]);

    const last = steps.length - 1;
    return {
      path: vmf,
      scriptPath,
      scriptsDir,
      logicScriptId,
      classes,
      atSeconds: steps,
      markers: [
        ...classes.map((classname) => ({
          name: `${classname}_present`,
          pattern: `HSMCP_CLASS ${last} ${classname} [1-9][0-9]*`,
          withinSeconds: steps[last]! + 60,
        })),
        {
          name: "class_probe_done",
          pattern: "HSMCP_CLASS_DONE",
          withinSeconds: steps[last]! + 60,
        },
      ],
      nextStep:
        "Compile the VMF, then call run_map_test with `scriptsDir` set to this directory and " +
        "`markerOrder: \"any\"`. A missing `<class>_present` marker means the count was zero " +
        "at the final sample; the raw counts are in the console log.",
    };
  },
});

export const classProbeTools = [writeClassProbeTool];
