/**
 * Model metadata that is not geometry: attachments and hitbox sets.
 *
 * Both live in the `.mdl` header and are relative to their own structs. Attachments carry a
 * `matrix3x4_t` whose three rows are the local axes and whose fourth column is the local
 * position. L4D2's studiomdl reads `$attachment ... rotate A B C` as `Rz(B) * Ry(A) * Rx(C)`,
 * so the QC arguments are pitch, yaw, roll even though the matrix decomposes to roll, pitch,
 * yaw (the order this module returns and SMD uses).
 *
 * Hitbox sizes are fixed for version 49: 92 bytes per attachment, 68 per hitbox. The fields
 * after `bbmax` (pitch/yaw/roll, one unknown float and three ints) are read but not written:
 * L4D2's compiler rejects them in a `$hbox` line.
 */
import type { Vec3 } from "./mdlmesh.js";

/** `STUDIOHDR_FLAGS_AUTOGENERATED_HITBOX`: studiomdl rebuilds these on every compile. */
export const AUTOGENERATED_HITBOX = 1 << 0;

const ATTACHMENT_SIZE = 92;
const HITBOX_SIZE = 68;

export interface MdlAttachment {
  index: number;
  name: string;
  flags: number;
  bone: number;
  position: Vec3;
  /** Local rotation as XYZ Euler radians in `Rz * Ry * Rx` order. */
  rotation: Vec3;
}

export interface MdlHitbox {
  name: string;
  group: number;
  bone: number;
  min: Vec3;
  max: Vec3;
}

export interface MdlHitboxSet {
  name: string;
  hitboxes: MdlHitbox[];
}

/** One `mstudiomodelgroup_t`, i.e. one `$includemodel` entry. */
export interface MdlIncludedModel {
  index: number;
  /** Often empty; the QC only needs the model path. */
  label: string;
  model: string;
}

function readName(bytes: Buffer, offset: number): string {
  if (offset <= 0 || offset >= bytes.length) return "";
  const end = bytes.indexOf(0, offset);
  return bytes.subarray(offset, end < 0 ? bytes.length : end).toString("latin1");
}

function clampUnit(value: number): number {
  return Math.min(1, Math.max(-1, value));
}

/**
 * Decomposes a row-major rotation matrix into Source Euler angles.
 *
 * `studiomdl` builds `R = Rz(yaw) * Ry(pitch) * Rx(roll)`, so `M[2][0]` is `-sin(pitch)`,
 * `M[2][1]`/`M[2][2]` give roll and `M[1][0]`/`M[0][0]` give yaw. At the poles roll and yaw
 * are not independent; yaw is set to zero and roll carries the combined turn.
 */
export function matrixToEuler(matrix: readonly number[]): Vec3 {
  const sinPitch = clampUnit(-matrix[6]!);
  const pitch = Math.asin(sinPitch);
  // Near the poles roll and yaw are not separable; yaw is set to zero and roll carries the
  // combined turn. The threshold keeps a noisy `0.999999` from producing arbitrary angles.
  if (Math.abs(sinPitch) > 0.9999) {
    const r01 = matrix[1]!;
    const r11 = matrix[4]!;
    return [Math.atan2(sinPitch > 0 ? r01 : -r01, r11), pitch, 0];
  }
  return [
    Math.atan2(matrix[7]!, matrix[8]!),
    pitch,
    Math.atan2(matrix[3]!, matrix[0]!),
  ];
}

export function readAttachments(mdl: Buffer): MdlAttachment[] {
  const count = mdl.readInt32LE(240);
  const offset = mdl.readInt32LE(244);
  if (count <= 0 || count > 10_000 || offset <= 0 || offset >= mdl.length) return [];
  const attachments: MdlAttachment[] = [];
  for (let index = 0; index < count; index += 1) {
    const base = offset + index * ATTACHMENT_SIZE;
    if (base + ATTACHMENT_SIZE > mdl.length) break;
    const bone = mdl.readInt32LE(base + 8);
    const matrix = Array.from({ length: 9 }, (_, i) => {
      const row = Math.trunc(i / 3);
      const column = i % 3;
      // Skip the fourth column (translation) at the end of each row in memory.
      return mdl.readFloatLE(base + 12 + row * 16 + column * 4);
    });
    attachments.push({
      index,
      name: readName(mdl, base + mdl.readInt32LE(base)),
      flags: mdl.readInt32LE(base + 4),
      bone,
      position: [
        mdl.readFloatLE(base + 24),
        mdl.readFloatLE(base + 40),
        mdl.readFloatLE(base + 56),
      ],
      rotation: matrixToEuler(matrix),
    });
  }
  return attachments;
}

/**
 * Included models (`$includemodel`): the count is at 336 and the list at 340 in v49.
 *
 * Each entry is two relative string offsets. This is how a survivor model reuses another
 * model's 1,000+ sequences; a decompiler that ignores it writes a QC whose sequences point
 * at animation SMDs it never produced.
 */
export function readIncludedModels(mdl: Buffer): MdlIncludedModel[] {
  if (mdl.length < 344) return [];
  const count = mdl.readInt32LE(336);
  const offset = mdl.readInt32LE(340);
  if (count <= 0 || count > 4096 || offset <= 0 || offset >= mdl.length) return [];
  const models: MdlIncludedModel[] = [];
  for (let index = 0; index < count; index += 1) {
    const base = offset + index * 8;
    if (base + 8 > mdl.length) break;
    const labelOffset = mdl.readInt32LE(base);
    const nameOffset = mdl.readInt32LE(base + 4);
    models.push({
      index,
      label: labelOffset > 0 ? readName(mdl, base + labelOffset) : "",
      model: nameOffset > 0 ? readName(mdl, base + nameOffset) : "",
    });
  }
  return models;
}

export function readHitboxSets(mdl: Buffer): MdlHitboxSet[] {
  const count = mdl.readInt32LE(172);
  const offset = mdl.readInt32LE(176);
  if (count <= 0 || count > 10_000 || offset <= 0 || offset >= mdl.length) return [];
  const sets: MdlHitboxSet[] = [];
  for (let index = 0; index < count; index += 1) {
    const base = offset + index * 12;
    if (base + 12 > mdl.length) break;
    const name = readName(mdl, base + mdl.readInt32LE(base));
    const hitboxCount = mdl.readInt32LE(base + 4);
    const hitboxOffset = mdl.readInt32LE(base + 8);
    const hitboxes: MdlHitbox[] = [];
    for (let i = 0; i < hitboxCount; i += 1) {
      const at = base + hitboxOffset + i * HITBOX_SIZE;
      if (at + HITBOX_SIZE > mdl.length) break;
      const nameRelative = mdl.readInt32LE(at + 32);
      const bone = mdl.readInt32LE(at);
      hitboxes.push({
        name: readName(mdl, at + nameRelative),
        group: mdl.readInt32LE(at + 4),
        bone,
        min: [mdl.readFloatLE(at + 8), mdl.readFloatLE(at + 12), mdl.readFloatLE(at + 16)],
        max: [mdl.readFloatLE(at + 20), mdl.readFloatLE(at + 24), mdl.readFloatLE(at + 28)],
      });
    }
    sets.push({ name, hitboxes });
  }
  return sets;
}
