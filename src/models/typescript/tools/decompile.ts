/** `flexcontroller` and `%rule` lines rebuilt from the MDL's controller and postfix-op lists. */
function flexQcLines(
  geometry: ModelGeometry,
  warnings: string[],
  declaredDescriptors: ReadonlySet<string>,
): string[] {
  const lines: string[] = [];
  for (const controller of geometry.flex.controllers) {
    const type = controller.type.replace(/["\s]+/g, "");
    const name = controller.name.replace(/"/g, "");
    if (!type || !name) continue;
    lines.push(
      `\tflexcontroller ${type} range ${fmt(controller.min)} ${fmt(controller.max)} "${name}"`,
    );
  }
  for (const rule of geometry.flex.rules) {
    const descriptor = geometry.flex.descriptors[rule.flex];
    if (!descriptor) continue;
    const safe = descriptor.replace(/[^A-Za-z0-9_]/g, "");
    // A rule can drive a descriptor that no flex frame moves (`%biter = bite` on the
    // survivors). That descriptor exists only as a local variable, and studiomdl rejects
    // the rule with "Rule for unknown flex" unless `localvar` names it first.
    if (!declaredDescriptors.has(descriptor)) lines.push(`\tlocalvar ${safe}`);
    const expression = flexRuleExpression(rule, geometry.flex);
    if (!expression) {
      warnings.push(
        `Flex rule for "${descriptor}" uses an operator this decompiler does not know; ` +
          "the rule was not written.",
      );
      continue;
    }
    lines.push(`\t%${safe} = ${expression}`);
  }
  return lines;
}

function qcText(
  geometry: ModelGeometry,
  header: ReturnType<typeof readModelHeaderInfo>,
  bones: ModelBone[],
  bodyFile: string,
  targetModelName: string,
  collision: (CollisionModel & { smdName: string }) | null,
  sequences: Array<{
    name: string;
    fps: number;
    frameCount: number;
    activityName: string;
    loop: boolean;
    files: string[];
    blendWidth?: number;
    blends: Array<{ name: string; start: number; end: number }>;
    fadeIn: number;
    fadeOut: number;
    events: Array<{ name: string; frame: number; options: string }>;
  }>,
  attachments: MdlAttachment[],
  hitboxSets: MdlHitboxSet[],
  autoHitboxes: boolean,
  bodyGroups: BodyGroupDef[],
  flexBodies: Map<string, FlexBodyDef>,
  lodBlocks: LodBlockDef[],
  shadowReplacements: LodReplacement[],
  ikChains: MdlIkChain[],
  ikLocks: MdlIkLock[],
  jiggles: MdlJiggleBone[],
  proceduralVrd: string | null,
  includedModels: MdlIncludedModel[],
  defineBones: string[] | null,
  warnings: string[],
): string {
  const modelname = targetModelName
    .replace(/\\/g, "/")
    .replace(/^models\//i, "")
    .replace(/\.mdl$/i, "");
  const lines: string[] = [
    `// Decompiled by L4D2-HSMCP: reference meshes, bodygroup alternatives and LOD replacements.`,
    `// Sequences stored in the .mdl are decoded; attachments, custom hitboxes and skin families`,
    `// are written. Flex deltas are written as VTA frames; bodygroup presets are not.`,
    "",
    `$modelname "${modelname}.mdl"`,
    ...(proceduralVrd ? [`$proceduralbones "${proceduralVrd}"`] : []),
  ];

  // An included animation model is how a survivor reuses another model's sequences; without
  // it a decompiled QC references animation SMDs it never produced, and studiomdl drops them.
  for (const include of includedModels) {
    if (include.model) lines.push(`$includemodel "${include.model.replace(/"/g, "")}"`);
  }
  if (defineBones && defineBones.length > 0) {
    // Generated from the bind pose in the verified `(y, z, x)` degree order.
    lines.push(...defineBones);
  }
  // `$ikchain` has to precede the sequences that use it. The end bone is the last link;
  // the knee vector is the first link's ideal bending direction, rounded to 3 dp as the
  // compiler writes it.
  for (const chain of ikChains) {
    const endBone = bones[chain.bones[chain.bones.length - 1] ?? -1];
    if (!endBone) continue;
    const knee = chain.knee.map((value) => Number(value.toFixed(3)));
    lines.push(
      `$ikchain "${chain.name.replace(/"/g, "")}" "${endBone.name.replace(/"/g, "")}" knee ` +
        `${fmt(knee[0]!)} ${fmt(knee[1]!)} ${fmt(knee[2]!)}`,
    );
  }
  for (const lock of ikLocks) {
    const chain = ikChains[lock.chain];
    if (!chain) continue;
    lines.push(
      `$ikautoplaylock "${chain.name.replace(/"/g, "")}" ` +
        `${fmt(lock.positionWeight)} ${fmt(lock.localQWeight)}`,
    );
  }
  for (const jiggle of jiggles) lines.push(...jiggleQcLines(jiggle));
  if (jiggles.length > 0) lines.push("");

  const flexBlock = (body: FlexBodyDef): string[] => [
    `\tflexfile "${body.vta}"`,
    "\t{",
    ...body.frames.map(
      (frame) => `\t\tflex "${frame.name.replace(/"/g, "")}" frame ${frame.frame}`,
    ),
    "\t}",
    ...flexQcLines(
      geometry,
      warnings,
      new Set(body.frames.map((frame) => frame.name)),
    ),
  ];
  const modelBlock = (name: string, file: string, body: FlexBodyDef): string[] => [
    `$model "${name.replace(/"/g, "")}" "${file}" {`,
    ...flexBlock(body),
    "}",
  ];

  if (bodyGroups.length === 0) {
    const flex = flexBodies.get(bodyFile);
    if (flex) lines.push(...modelBlock("Body", bodyFile, flex));
    else lines.push(`$body "Body" "${bodyFile}"`);
  } else {
    for (const group of bodyGroups) {
      // `$bodygroup` only understands `studio`/`blank`; a flex has to be a `$model`, which
      // can name one file. Source itself cannot give alternatives their own flexes, so the
      // handler warns when a flex is not model 0 of its part.
      const first = group.models[0]?.file;
      const flex = first ? flexBodies.get(first) : undefined;
      if (flex && first) {
        lines.push(...modelBlock(group.name, first, flex));
        continue;
      }
      lines.push(`$bodygroup "${group.name.replace(/"/g, "")}"`, "{");
      for (const model of group.models) {
        lines.push(model.file ? `\tstudio "${model.file}"` : "\tblank");
      }
      lines.push("}");
    }
  }
  for (const dir of materialDirs(geometry)) lines.push(`$cdmaterials "${dir}"`);
  if (header?.surfaceProp) lines.push(`$surfaceprop "${header.surfaceProp}"`);
  if ((header?.flags ?? 0) & STATIC_PROP) lines.push("$staticprop");
  if (header && (header.contents & 1) !== 0) lines.push('$contents "solid"');
  if (header) {
    const nonZero = (values: number[]): boolean => values.some((value) => Math.abs(value) > 1e-6);
    if (nonZero([...header.hull.min, ...header.hull.max])) {
      lines.push(
        `$bbox ${header.hull.min.map(fmt).join(" ")} ${header.hull.max.map(fmt).join(" ")}`,
      );
    }
    if (nonZero([...header.viewBox.min, ...header.viewBox.max])) {
      lines.push(
        `$cbox ${header.viewBox.min.map(fmt).join(" ")} ${header.viewBox.max.map(fmt).join(" ")}`,
      );
    }
  }
  if ((header?.flags ?? 0) & TRANSLUCENT_TWOPASS) lines.push("$mostlyopaque");
  else if ((header?.flags ?? 0) & FORCE_OPAQUE) lines.push("$opaque");

  // Skin families are `$texturegroup` rows of material names. The SMD names each material by
  // its path; the compiler matches these rows by bare file name under `$cdmaterials`.
  if (geometry.skins.length > 1 && geometry.skins[0]!.length > 0) {
    const lastName = (index: number): string => {
      const material = (geometry.materials[index] ?? "").replace(/\\/g, "/");
      const leaf = material.slice(material.lastIndexOf("/") + 1);
      return leaf.replace(/\.vmt$/i, "").replace(/"/g, "");
    };
    lines.push("", `$texturegroup "skinfamilies"`, "{");
    for (const family of geometry.skins) {
      lines.push(`\t{ ${family.map((index) => `"${lastName(index)}"`).join(" ")} }`);
    }
    lines.push("}");
  }

  for (const block of lodBlocks) {
    const distance = Number.isInteger(block.distance)
      ? String(block.distance)
      : fmt(block.distance);
    lines.push("", `$lod ${distance}`, "{");
    for (const replacement of block.replacements) {
      lines.push(`\treplacemodel "${replacement.from}" "${replacement.to}"`);
    }
    lines.push("}");
  }
  if (shadowReplacements.length > 0) {
    lines.push("", "$shadowlod", "{");
    for (const replacement of shadowReplacements) {
      lines.push(`\treplacemodel "${replacement.from}" "${replacement.to}"`);
    }
    lines.push("}");
  }

  // studiomdl refuses a model with no sequences. A decoded clip is written as a real
  // sequence; otherwise the reference SMD is a single-frame bind pose, so a one-frame idle is
  // honest: it compiles, and it is not pretending to be the original animation set.
  if (sequences.length === 0) {
    lines.push(`$sequence "idle" "${bodyFile}" fps 1`);
  } else {
    for (const sequence of sequences) {
      const name = sequence.name.replace(/"/g, "");
      const needsBlock =
        sequence.events.length > 0 ||
        Math.abs(sequence.fadeIn - 0.2) > 1e-6 ||
        Math.abs(sequence.fadeOut - 0.2) > 1e-6;
      if (sequence.files.length <= 1 && sequence.blends.length === 0 && !needsBlock) {
        const args = [
          `"${name}"`,
          `"${sequence.files[0] ?? sequence.name}"`,
          `fps ${fmt(sequence.fps)}`,
        ];
        if (sequence.activityName) args.push(`activity ${sequence.activityName}`);
        if (sequence.loop) args.push("loop");
        lines.push(`$sequence ${args.join(" ")}`);
        continue;
      }
      // A multi-blend sequence is a `$sequence` block: all source SMDs, then the blend
      // width and the pose-parameter ranges. `blendwidth` is only needed when the two group
      // sizes differ, which is how studiomdl decides the rows. A clip with events or
      // non-default fades also needs a block, because none of those fit on the one-line form.
      lines.push(`$sequence "${name}" {`);
      if (sequence.files.length > 0) {
        lines.push(`\t${sequence.files.map((file) => `"${file}"`).join(" ")}`);
      }
      lines.push(`\tfps ${fmt(sequence.fps)}`);
      if (sequence.activityName) lines.push(`\tactivity ${sequence.activityName}`);
      if (sequence.loop) lines.push("\tloop");
      if (sequence.blendWidth !== undefined) lines.push(`\tblendwidth ${sequence.blendWidth}`);
      for (const blend of sequence.blends) {
        lines.push(`\tblend "${blend.name}" ${fmt(blend.start)} ${fmt(blend.end)}`);
      }
      if (Math.abs(sequence.fadeIn - 0.2) > 1e-6) lines.push(`\tfadein ${fmt(sequence.fadeIn)}`);
      if (Math.abs(sequence.fadeOut - 0.2) > 1e-6) lines.push(`\tfadeout ${fmt(sequence.fadeOut)}`);
      for (const event of sequence.events) {
        const options = event.options ? ` "${event.options.replace(/"/g, "'")}"` : "";
        lines.push(`\t{ event ${event.name} ${event.frame}${options} }`);
      }
      lines.push("}");
    }
  }

  const illum = header?.illuminationPosition;
  if (illum && illum.some((value) => Math.abs(value) > 1e-6)) {
    lines.push(`$illumposition ${fmt(illum[1])} ${fmt(-illum[0])} ${fmt(illum[2])}`);
  }
  const eye = header?.eyePosition;
  if (eye && eye.some((value) => Math.abs(value) > 1e-6)) {
    lines.push(`$eyeposition ${fmt(eye[1])} ${fmt(-eye[0])} ${fmt(eye[2])}`);
  }

  const attachmentLines: string[] = [];
  for (const attachment of attachments) {
    // The illumination point is written as `$illumposition`; a second copy as an attachment
    // makes HLMV show two of them and is not needed to compile.
    if (attachment.name.toLowerCase() === "illumposition") continue;
    const bone = bones[attachment.bone];
    if (!bone) continue;
    const name = attachment.name
      ? `"${attachment.name.replace(/"/g, "")}"`
      : String(attachment.index);
    const [roll, pitch, yaw] = attachment.rotation;
    const degrees = (value: number): string => fmt((value * 180) / Math.PI);
    // L4D2's QC parser reads these three numbers as pitch, yaw, roll (its matrix is
    // Rz(yaw) * Ry(pitch) * Rx(roll)), not as the SMD roll/pitch/yaw order.
    attachmentLines.push(
      `$attachment ${name} "${bone.name.replace(/"/g, "")}" ` +
        `${fmt(attachment.position[0])} ${fmt(attachment.position[1])} ${fmt(attachment.position[2])} ` +
        `rotate ${degrees(pitch)} ${degrees(yaw)} ${degrees(roll)}`,
    );
  }
  if (attachmentLines.length > 0) lines.push("", ...attachmentLines);

  if (!autoHitboxes && hitboxSets.length > 0) {
    const hitboxLines: string[] = [];
    for (const [setIndex, set] of hitboxSets.entries()) {
      if (set.hitboxes.length === 0) continue;
      hitboxLines.push(`$hboxset "${(set.name || `hitboxset_${setIndex}`).replace(/"/g, "")}"`);
      for (const hitbox of set.hitboxes) {
        const bone = bones[hitbox.bone];
        if (!bone) continue;
        hitboxLines.push(
          `$hbox ${hitbox.group} "${bone.name.replace(/"/g, "")}" ` +
            `${fmt(hitbox.min[0])} ${fmt(hitbox.min[1])} ${fmt(hitbox.min[2])} ` +
            `${fmt(hitbox.max[0])} ${fmt(hitbox.max[1])} ${fmt(hitbox.max[2])}`,
        );
      }
    }
    if (hitboxLines.length > 0) lines.push("", ...hitboxLines);
  }

  if (collision) {
    const ragdoll = collision.ragdoll;
    const solids = ragdoll?.solids ?? [];
    const mostUsed = (values: number[]): number => {
      const counts = new Map<number, number>();
      for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
      let best = 0;
      let bestCount = -1;
      for (const [value, count] of counts) {
        if (count > bestCount) {
          best = value;
          bestCount = count;
        }
      }
      return best;
    };
    const common = {
      inertia: mostUsed(solids.map((solid) => solid.inertia)),
      damping: mostUsed(solids.map((solid) => solid.damping)),
      rotdamping: mostUsed(solids.map((solid) => solid.rotdamping)),
    };

    lines.push(
      "",
      `$${collision.jointed ? "collisionjoints" : "collisionmodel"} "${collision.smdName}"`,
      "{",
      `\t$mass ${fmt(collision.mass)}`,
    );
    if (solids.length > 0) {
      lines.push(
        `\t$inertia ${fmt(common.inertia)}`,
        `\t$damping ${fmt(common.damping)}`,
        `\t$rotdamping ${fmt(common.rotdamping)}`,
      );
    }
    if (collision.jointed && ragdoll?.rootName) {
      lines.push(`\t$rootbone "${ragdoll.rootName}"`);
    }
    if (collision.concave) {
      lines.push("\t$concave");
      if (collision.jointed) lines.push(`\t$maxconvexpieces ${collision.maxConvexPieces}`);
    }
    if (collision.jointed && collision.pieces.some((pieces) => pieces > 1)) {
      lines.push("\t$concaveperjoint");
    }
    if (collision.jointed) {
      for (let index = 0; index < solids.length; index += 1) {
        const solid = solids[index]!;
        const name = solid.name.replace(/"/g, "");
        if (solid.massbias > 0) lines.push(`\t$jointmassbias "${name}" ${fmt(solid.massbias)}`);
        if (solid.damping !== common.damping) lines.push(`\t$jointdamping "${name}" ${fmt(solid.damping)}`);
        if (solid.inertia !== common.inertia) lines.push(`\t$jointinertia "${name}" ${fmt(solid.inertia)}`);
        if (solid.rotdamping !== common.rotdamping) {
          lines.push(`\t$jointrotdamping "${name}" ${fmt(solid.rotdamping)}`);
        }
        const constraint = ragdoll?.constraints.find((entry) => entry.child === index);
        if (!constraint) continue;
        for (const axis of ["x", "y", "z"] as const) {
          const [min, max] = constraint.limits[axis];
          // studiomdl divides the QC friction by 5, so the file stores it multiplied.
          const friction = constraint.friction[axis] * 5;
          lines.push(
            `\t$jointconstrain "${name}" ${axis} limit ${fmt(min)} ${fmt(max)} ${fmt(friction)}`,
          );
        }
      }
      if (ragdoll && !ragdoll.selfCollisions) {
        lines.push("\t$noselfcollisions");
      } else if (ragdoll?.collisionPairs?.length) {
        lines.push("");
        for (const [a, b] of ragdoll.collisionPairs) {
          const first = solids[a];
          const second = solids[b];
          if (first && second) {
            lines.push(
              `\t$jointcollide "${first.name.replace(/"/g, "")}" "${second.name.replace(/"/g, "")}"`,
            );
          }
        }
      }
    }
    lines.push("}");
  }

  // `$keyvalues` is the only QC carrier for `prop_data` and weapon particle attachments.
  // The header stores the block as `mdlkeyvalue { ... }`; `readModelHeaderInfo` strips that
  // wrapper, so the inner text goes in verbatim.
  if (header?.keyvalues) {
    lines.push("", "$keyvalues", "{");
    for (const line of header.keyvalues.split("\n")) lines.push(`\t${line}`);
    lines.push("}");
  }
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function keyValueNumber(text: string | null, key: string, fallback: number): number {
  if (!text) return fallback;
  const match = new RegExp(`"${key}"\\s+"([^"]*)"`, "i").exec(text);
  const value = match ? Number.parseFloat(match[1]!) : NaN;
  return Number.isFinite(value) ? value : fallback;
}

