const STATIC_PROP = 1 << 4;
const FORCE_OPAQUE = 1 << 2;
const TRANSLUCENT_TWOPASS = 1 << 3;

function normalizeModelPath(model: string): string {
  let path = model.replace(/\\/g, "/").replace(/^\/+/, "");
  if (!path.toLowerCase().endsWith(".mdl")) path += ".mdl";
  if (!path.toLowerCase().startsWith("models/")) path = `models/${path}`;
  return path;
}

/** Reads a null-terminated MDL string at an absolute offset. */
function readMdlCString(bytes: Buffer, offset: number): string {
  if (offset < 0 || offset >= bytes.length) return "";
  const end = bytes.indexOf(0, offset);
  return bytes.subarray(offset, end < 0 ? bytes.length : end).toString("latin1");
}

function safeBase(path: string): string {
  return (
    basename(path, ".mdl")
      .replace(/[^A-Za-z0-9_]+/g, "_")
      .replace(/^_+|_+$/g, "")
      .slice(0, 64) || "model"
  );
}

function fmt(value: number): string {
  return Number.isFinite(value) ? value.toFixed(6) : "0.000000";
}

function chooseBone(vertex: ModelVertex, boneCount: number): number {
  if (vertex.bones) {
    for (let i = 0; i < (vertex.boneCount ?? 0); i += 1) {
      const bone = vertex.bones[i];
      if (bone !== undefined && bone >= 0 && bone < boneCount) return bone;
    }
  }
  return 0;
}

function boneLinks(vertex: ModelVertex, boneCount: number): Array<[number, number]> {
  const links: Array<[number, number]> = [];
  const count = Math.min(3, vertex.boneCount ?? 0);
  if (vertex.bones && vertex.weights) {
    for (let i = 0; i < count; i += 1) {
      const bone = vertex.bones[i];
      const weight = vertex.weights[i];
      if (bone === undefined || weight === undefined) continue;
      if (bone < 0 || bone >= boneCount || !(weight > 0)) continue;
      links.push([bone, weight]);
    }
  }
  if (links.length === 0) links.push([0, 1]);
  return links;
}

function writeVertexLine(vertex: ModelVertex, boneCount: number, staticProp: boolean): string {
  const links = boneLinks(vertex, boneCount);
  const parent = chooseBone(vertex, boneCount);
  const p = vertex.position;
  const n = vertex.normal;
  const [u, v] = vertex.uv;
  // A static prop's VVD is stored with the X/Y axes swapped relative to SMD; Crowbar calls
  // this the static-prop reference-mesh rotation. Applying it here is what makes the
  // recompiled model's bounds match the source instead of coming out 90 degrees turned.
  const position: Vec3 = staticProp ? [p[1], -p[0], p[2]] : p;
  const normal: Vec3 = staticProp ? [n[1], -n[0], n[2]] : n;
  return [
    "  ",
    parent,
    " ",
    fmt(position[0]),
    " ",
    fmt(position[1]),
    " ",
    fmt(position[2]),
    " ",
    fmt(normal[0]),
    " ",
    fmt(normal[1]),
    " ",
    fmt(normal[2]),
    " ",
    fmt(u),
    " ",
    fmt(1 - v),
    " ",
    links.length,
    ...links.flatMap(([bone, weight]) => [" ", bone, " ", fmt(weight)]),
  ].join("");
}

function referenceSmd(
  meshes: ModelMesh[],
  materials: string[],
  bones: ModelBone[],
  staticProp: boolean,
): string {
  const boneCount = Math.max(1, bones.length);
  const lines: string[] = ["version 1", "nodes"];
  if (bones.length === 0) {
    lines.push('0 "static_prop" -1');
  } else {
    for (const bone of bones) {
      lines.push(`${bone.index} "${bone.name.replace(/"/g, "")}" ${bone.parent}`);
    }
  }
  lines.push("end", "skeleton", "time 0");
  if (bones.length === 0) {
    lines.push("0 0.000000 0.000000 0.000000 0.000000 0.000000 0.000000");
  } else {
    for (const bone of bones) {
      const [rx, ry, rz] = quaternionToEuler(bone.rotation);
      lines.push(
        `${bone.index} ${fmt(bone.position[0])} ${fmt(bone.position[1])} ${fmt(bone.position[2])} ` +
          `${fmt(rx)} ${fmt(ry)} ${fmt(rz)}`,
      );
    }
  }
  lines.push("end", "triangles");

  for (const mesh of meshes) {
    const material = materials[mesh.materialIndex] ?? "material";
    const smdMaterial = material.split("/").pop() ?? material;
    for (let t = 0; t + 2 < mesh.triangles.length; t += 3) {
      // A material line before each triangle is what the stock SMD reader accepts; a single
      // material line followed by many triangles is legal in the format but this compiler
      // treats the following lines as new materials.
      lines.push(smdMaterial);
      for (let corner = 0; corner < 3; corner += 1) {
        const vertex = mesh.vertices[mesh.triangles[t + corner]!]!;
        lines.push(writeVertexLine(vertex, boneCount, staticProp));
      }
    }
  }
  lines.push("end");
  return `${lines.join("\n")}\n`;
}

function animationSmd(bones: ModelBone[], frames: AnimationFrame[]): string {
  const lines: string[] = ["version 1", "nodes"];
  if (bones.length === 0) {
    lines.push('0 "static_prop" -1');
  } else {
    for (const bone of bones) {
      lines.push(`${bone.index} "${bone.name.replace(/"/g, "")}" ${bone.parent}`);
    }
  }
  lines.push("end", "skeleton");
  const boneCount = Math.max(1, bones.length);
  for (let frameIndex = 0; frameIndex < frames.length; frameIndex += 1) {
    const frame = frames[frameIndex]!;
    // SMD `time` is a frame number, not seconds; the QC's `fps` converts it.
    lines.push(`time ${frameIndex}`);
    for (let index = 0; index < boneCount; index += 1) {
      const bone = frame.bones[index] ?? { position: [0, 0, 0] as Vec3, rotation: [0, 0, 0] as Vec3 };
      lines.push(
        `${index} ${fmt(bone.position[0])} ${fmt(bone.position[1])} ${fmt(bone.position[2])} ` +
          `${fmt(bone.rotation[0])} ${fmt(bone.rotation[1])} ${fmt(bone.rotation[2])}`,
      );
    }
  }
  lines.push("end");
  return `${lines.join("\n")}\n`;
}

function collisionSmd(phyBytes: Buffer, staticProp: boolean): { text: string; triangles: number } | null {
  const geometry = readPhyGeometry(phyBytes);
  if (geometry.solids.length === 0) return null;
  const lines: string[] = [
    "version 1",
    "nodes",
    '0 "phys" -1',
    "end",
    "skeleton",
    "time 0",
    "0 0.000000 0.000000 0.000000 0.000000 0.000000 0.000000",
    "end",
    "triangles",
  ];
  let triangles = 0;
  for (const solid of geometry.solids) {
    for (const [a, b, c] of solid.triangles) {
      lines.push("phys");
      for (const index of [a, b, c]) {
        const vertex = solid.vertices[index];
        if (!vertex) continue;
        const position: Vec3 = staticProp ? [vertex[1], -vertex[0], vertex[2]] : vertex;
        lines.push(
          `  0 ${fmt(position[0])} ${fmt(position[1])} ${fmt(position[2])} ` +
            `0.000000 0.000000 1.000000 0.000000 0.000000 1 0 1.000000`,
        );
      }
      triangles += 1;
    }
  }
  lines.push("end");
  return { text: `${lines.join("\n")}\n`, triangles };
}

function materialDirs(geometry: ModelGeometry): string[] {
  const dirs = new Set<string>();
  for (const material of geometry.materials) {
    const cut = material.lastIndexOf("/");
    if (cut > 0) dirs.add(material.slice(0, cut + 1));
  }
  return [...dirs].sort();
}

function safeToken(value: string, fallback: string): string {
  const leaf = value.replace(/\\/g, "/").split("/").pop() ?? "";
  return (
    leaf
      .replace(/\.(smd|dmx)$/i, "")
      .replace(/[^A-Za-z0-9_]+/g, "_")
      .replace(/^_+|_+$/g, "")
      .slice(0, 40) || fallback
  );
}

interface LodReplacement {
  from: string;
  to: string;
}

interface LodBlockDef {
  distance: number;
  replacements: LodReplacement[];
}

interface BodyGroupDef {
  name: string;
  models: Array<{ file: string | null }>;
}

interface FlexBodyDef {
  /** SMD the flex belongs to; the key of the map is this file name. */
  vta: string;
  frames: VtaFrame[];
}

/** `flexcontroller` and `%rule` lines rebuilt from the MDL's controller and postfix-op lists. */
function flexQcLines(geometry: ModelGeometry, warnings: string[]): string[] {
  const lines: string[] = [];
  for (const controller of geometry.flex.controllers) {
    const type = controller.type.replace(/["\s]+/g, "");
    const name = controller.name.replace(/"/g, "");
    if (!type || !name) continue;
    lines.push(
      `\tflexcontroller ${type} range ${fmt(controller.min)} ${fmt(controller.max)} "${name}"`,
    );
  }
  for (const rule of geometry.flex.rules) {
    const descriptor = geometry.flex.descriptors[rule.flex];
    if (!descriptor) continue;
    const expression = flexRuleExpression(rule, geometry.flex);
    if (!expression) {
      warnings.push(
        `Flex rule for "${descriptor}" uses an operator this decompiler does not know; ` +
          "the rule was not written.",
      );
      continue;
    }
    lines.push(`\t%${descriptor.replace(/[^A-Za-z0-9_]/g, "")} = ${expression}`);
  }
  return lines;
}

function qcText(
  geometry: ModelGeometry,
  header: ReturnType<typeof readModelHeaderInfo>,
  bones: ModelBone[],
  bodyFile: string,
  targetModelName: string,
  collision: { smdName: string; mass: number; concave: boolean } | null,
  sequences: Array<{
    name: string;
    fps: number;
    activityName: string;
    loop: boolean;
    files: string[];
    blendWidth?: number;
    blends: Array<{ name: string; start: number; end: number }>;
  }>,
  attachments: MdlAttachment[],
  hitboxSets: MdlHitboxSet[],
  autoHitboxes: boolean,
  bodyGroups: BodyGroupDef[],
  flexBodies: Map<string, FlexBodyDef>,
  lodBlocks: LodBlockDef[],
  shadowReplacements: LodReplacement[],
  warnings: string[],
): string {
  const modelname = targetModelName
    .replace(/\\/g, "/")
    .replace(/^models\//i, "")
    .replace(/\.mdl$/i, "");
  const lines: string[] = [
    `// Decompiled by L4D2-HSMCP: reference meshes, bodygroup alternatives and LOD replacements.`,
    `// Sequences stored in the .mdl are decoded; attachments, custom hitboxes and skin families`,
    `// are written. Flex deltas are written as VTA frames; bodygroup presets are not.`,
    "",
    `$modelname "${modelname}.mdl"`,
  ];

  const flexBlock = (body: FlexBodyDef): string[] => [
    `\tflexfile "${body.vta}"`,
    "\t{",
    ...body.frames.map(
      (frame) => `\t\tflex "${frame.name.replace(/"/g, "")}" frame ${frame.frame}`,
    ),
    "\t}",
    ...flexQcLines(geometry, warnings),
  ];
  const modelBlock = (name: string, file: string, body: FlexBodyDef): string[] => [
    `$model "${name.replace(/"/g, "")}" "${file}" {`,
    ...flexBlock(body),
    "}",
  ];

  if (bodyGroups.length === 0) {
    const flex = flexBodies.get(bodyFile);
    if (flex) lines.push(...modelBlock("Body", bodyFile, flex));
    else lines.push(`$body "Body" "${bodyFile}"`);
  } else {
    for (const group of bodyGroups) {
      // `$bodygroup` only understands `studio`/`blank`; a flex has to be a `$model`, which
      // can name one file. Source itself cannot give alternatives their own flexes, so the
      // handler warns when a flex is not model 0 of its part.
      const first = group.models[0]?.file;
      const flex = first ? flexBodies.get(first) : undefined;
      if (flex && first) {
        lines.push(...modelBlock(group.name, first, flex));
        continue;
      }
      lines.push(`$bodygroup "${group.name.replace(/"/g, "")}"`, "{");
      for (const model of group.models) {
        lines.push(model.file ? `\tstudio "${model.file}"` : "\tblank");
      }
      lines.push("}");
    }
  }
  for (const dir of materialDirs(geometry)) lines.push(`$cdmaterials "${dir}"`);
  if (header?.surfaceProp) lines.push(`$surfaceprop "${header.surfaceProp}"`);
  if ((header?.flags ?? 0) & STATIC_PROP) lines.push("$staticprop");
  if ((header?.flags ?? 0) & TRANSLUCENT_TWOPASS) lines.push("$mostlyopaque");
  else if ((header?.flags ?? 0) & FORCE_OPAQUE) lines.push("$opaque");

  // Skin families are `$texturegroup` rows of material names. The SMD names each material by
  // its path; the compiler matches these rows by bare file name under `$cdmaterials`.
  if (geometry.skins.length > 1 && geometry.skins[0]!.length > 0) {
    const lastName = (index: number): string => {
      const material = (geometry.materials[index] ?? "").replace(/\\/g, "/");
      const leaf = material.slice(material.lastIndexOf("/") + 1);
      return leaf.replace(/\.vmt$/i, "").replace(/"/g, "");
    };
    lines.push("", `$texturegroup "skinfamilies"`, "{");
    for (const family of geometry.skins) {
      lines.push(`\t{ ${family.map((index) => `"${lastName(index)}"`).join(" ")} }`);
    }
    lines.push("}");
  }

  for (const block of lodBlocks) {
    const distance = Number.isInteger(block.distance)
      ? String(block.distance)
      : fmt(block.distance);
    lines.push("", `$lod ${distance}`, "{");
    for (const replacement of block.replacements) {
      lines.push(`\treplacemodel "${replacement.from}" "${replacement.to}"`);
    }
    lines.push("}");
  }
  if (shadowReplacements.length > 0) {
    lines.push("", "$shadowlod", "{");
    for (const replacement of shadowReplacements) {
      lines.push(`\treplacemodel "${replacement.from}" "${replacement.to}"`);
    }
    lines.push("}");
  }

  // studiomdl refuses a model with no sequences. A decoded clip is written as a real
  // sequence; otherwise the reference SMD is a single-frame bind pose, so a one-frame idle is
  // honest: it compiles, and it is not pretending to be the original animation set.
  if (sequences.length === 0) {
    lines.push(`$sequence "idle" "${bodyFile}" fps 1`);
  } else {
    for (const sequence of sequences) {
      const name = sequence.name.replace(/"/g, "");
      if (sequence.files.length <= 1 && sequence.blends.length === 0) {
        const args = [
          `"${name}"`,
          `"${sequence.files[0] ?? sequence.name}"`,
          `fps ${fmt(sequence.fps)}`,
        ];
        if (sequence.activityName) args.push(`activity ${sequence.activityName}`);
        if (sequence.loop) args.push("loop");
        lines.push(`$sequence ${args.join(" ")}`);
        continue;
      }
      // A multi-blend sequence is a `$sequence` block: all source SMDs, then the blend
      // width and the pose-parameter ranges. `blendwidth` is only needed when the two group
      // sizes differ, which is how studiomdl decides the rows.
      lines.push(`$sequence "${name}" {`);
      lines.push(`\t${sequence.files.map((file) => `"${file}"`).join(" ")}`);
      lines.push(`\tfps ${fmt(sequence.fps)}`);
      if (sequence.activityName) lines.push(`\tactivity ${sequence.activityName}`);
      if (sequence.loop) lines.push("\tloop");
      if (sequence.blendWidth !== undefined) lines.push(`\tblendwidth ${sequence.blendWidth}`);
      for (const blend of sequence.blends) {
        lines.push(`\tblend "${blend.name}" ${fmt(blend.start)} ${fmt(blend.end)}`);
      }
      lines.push("}");
    }
  }

  const illum = header?.illuminationPosition;
  if (illum && illum.some((value) => Math.abs(value) > 1e-6)) {
    lines.push(`$illumposition ${fmt(illum[1])} ${fmt(-illum[0])} ${fmt(illum[2])}`);
  }
  const eye = header?.eyePosition;
  if (eye && eye.some((value) => Math.abs(value) > 1e-6)) {
    lines.push(`$eyeposition ${fmt(eye[1])} ${fmt(-eye[0])} ${fmt(eye[2])}`);
  }

  const attachmentLines: string[] = [];
  for (const attachment of attachments) {
    // The illumination point is written as `$illumposition`; a second copy as an attachment
    // makes HLMV show two of them and is not needed to compile.
    if (attachment.name.toLowerCase() === "illumposition") continue;
    const bone = bones[attachment.bone];
    if (!bone) continue;
    const name = attachment.name
      ? `"${attachment.name.replace(/"/g, "")}"`
      : String(attachment.index);
    const [roll, pitch, yaw] = attachment.rotation;
    const degrees = (value: number): string => fmt((value * 180) / Math.PI);
    // L4D2's QC parser reads these three numbers as pitch, yaw, roll (its matrix is
    // Rz(yaw) * Ry(pitch) * Rx(roll)), not as the SMD roll/pitch/yaw order.
    attachmentLines.push(
      `$attachment ${name} "${bone.name.replace(/"/g, "")}" ` +
        `${fmt(attachment.position[0])} ${fmt(attachment.position[1])} ${fmt(attachment.position[2])} ` +
        `rotate ${degrees(pitch)} ${degrees(yaw)} ${degrees(roll)}`,
    );
  }
  if (attachmentLines.length > 0) lines.push("", ...attachmentLines);

  if (!autoHitboxes && hitboxSets.length > 0) {
    const hitboxLines: string[] = [];
    for (const [setIndex, set] of hitboxSets.entries()) {
      if (set.hitboxes.length === 0) continue;
      hitboxLines.push(`$hboxset "${(set.name || `hitboxset_${setIndex}`).replace(/"/g, "")}"`);
      for (const hitbox of set.hitboxes) {
        const bone = bones[hitbox.bone];
        if (!bone) continue;
        hitboxLines.push(
          `$hbox ${hitbox.group} "${bone.name.replace(/"/g, "")}" ` +
            `${fmt(hitbox.min[0])} ${fmt(hitbox.min[1])} ${fmt(hitbox.min[2])} ` +
            `${fmt(hitbox.max[0])} ${fmt(hitbox.max[1])} ${fmt(hitbox.max[2])}`,
        );
      }
    }
    if (hitboxLines.length > 0) lines.push("", ...hitboxLines);
  }

  if (collision) {
    lines.push("", `$collisionmodel "${collision.smdName}"`, "{", `\t$mass ${fmt(collision.mass)}`);
    if (collision.concave) lines.push("\t$concave");
    lines.push("}");
  }
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function keyValueNumber(text: string | null, key: string, fallback: number): number {
  if (!text) return fallback;
  const match = new RegExp(`"${key}"\\s+"([^"]*)"`, "i").exec(text);
  const value = match ? Number.parseFloat(match[1]!) : NaN;
  return Number.isFinite(value) ? value : fallback;
}

